using System;
using System.Collections.Generic;
using AmbiECS.Extensions;
using AmbiECS.Glue;
using Unity.Collections;
using UnityEngine;

namespace AmbiECS.ReferenceDesign;

[AmbiSynchronization]
internal partial class Foo : AmbiMonoBehaviour<Foo>
{
    const int ALLOC_SIZE = 10;
    const int BAR_HANDLE_SIZE = 15;

    protected override int PreallocatedCapacity => ALLOC_SIZE;

    [InputBuffer]
    public static NativeArray<float> TargetVolumes;

    [ScratchBuffer(allocationCapacity: ALLOC_SIZE * 131), ManualExpand]
    public static NativeArray<int> ArbitraryScratchBuffer;

    [InputBuffer, SkipPostLoadSync]
    public static float[] ConstantFactors;

    [StatefulBuffer(1f)]
    public static NativeArray<float> CurrentVolumes;

    [InputBuffer(strideCapacity: BAR_HANDLE_SIZE)]
    public static NativeArray<AmbiHandle> BarHandleStrides;

    [field: SerializeField]
    [GluedProperty(nameof(TargetVolumes))]
    public partial float Volume { get; set; } = 1f; // if declared as a partial, the setter will be autogenerated

    [field: SerializeField]
    [GluedProperty(nameof(ConstantFactors))]
    public float ConstantFactor { get; set; } = 3.8f;

    // Array or List<T> pointing to a strided input buffer.
    // Take elements up to the declared input buffer stride capacity during synchronization and swap backs.
    // if T is of IAmbiRegistrant derivative class, gather their AmbiHandles
    // otherwise, T has to be an unmanaged struct or a blittable type.
    [GluedStride(nameof(BarHandleStrides))]
    public List<Bar> Bars = [];

    // Optionally declarable callbacks
    static void OnAllocation() { }

    static void OnDeallocation() { }

    void OnObjectLoadedToRow(int rowIndex) { }

    void OnObjectSyncedToRow(int rowIndex) { }

    static void OnRowSwapBack(int removedIndex, int lastIndex) { }

    static void OnCapacityIncreased(int newCapacity)
    {
        ArbitraryScratchBuffer.Resize(newCapacity * 131);
    }
}

internal partial class Foo
{
    public partial float Volume
    {
        get;
        set
        {
            field = value;

            if (IsRegistered)
                MarkDirty();
        }
    }

    // scratch buffer lifecycle, including resizing - is internal responsibility.
    protected override void AllocateColumns()
    {
        TargetVolumes = new(PreallocatedCapacity, Allocator.Persistent);
        ArbitraryScratchBuffer = new(ALLOC_SIZE * 131, Allocator.Persistent);
        ConstantFactors = new float[PreallocatedCapacity];
        CurrentVolumes = new(PreallocatedCapacity, Allocator.Persistent);
        BarHandleStrides = new(PreallocatedCapacity * BAR_HANDLE_SIZE, Allocator.Persistent);
    }

    protected override void DeallocateColumns()
    {
        TargetVolumes.Dispose();
        ArbitraryScratchBuffer.Dispose();
        ConstantFactors = null;
        CurrentVolumes.Dispose();
        BarHandleStrides.Dispose();
    }

    protected override void LoadObjectToRow()
    {
        ConstantFactors[SoAIndex] = ConstantFactor;
        CurrentVolumes[SoAIndex] = 1f;
    }

    protected override void SyncObjectToRow()
    {
        TargetVolumes[SoAIndex] = Volume;
        AmbiRefs.WriteStride(BarHandleStrides, SoAIndex, BAR_HANDLE_SIZE, Bars);
    }

    protected override void SwapBackRow(int removedIndex, int lastIndex)
    {
        if (removedIndex != lastIndex)
        {
            TargetVolumes[removedIndex] = TargetVolumes[lastIndex];
            CurrentVolumes[removedIndex] = CurrentVolumes[lastIndex];
            AmbiColumn.SwapBack(BarHandleStrides, removedIndex, lastIndex, BAR_HANDLE_SIZE);
        }
    }

    // during a main thread object registration overflow event,
    // copy all existing buffers into new buffers with double the previous capacity.
    static void IncreaseCapacity(int newCapacity)
    {
        TargetVolumes.Resize(newCapacity);
        Array.Resize(ref ConstantFactors, newCapacity);
        CurrentVolumes.Resize(newCapacity);
        BarHandleStrides.Resize(newCapacity * BAR_HANDLE_SIZE);
    }
}

[AmbiSynchronization, SkipAutoDirtyFlagging]
internal partial class Bar : AmbiMonoBehaviour<Bar>
{
    protected override int PreallocatedCapacity => 150;

    [InputBuffer]
    public static NativeArray<int> Contributions;

    [GluedProperty(nameof(Contributions))]
    public int Contribution { get; set; } = 12;
}

internal partial class Bar
{
    protected override void AllocateColumns()
    {
        Contributions = new(PreallocatedCapacity, Allocator.Persistent);
    }

    protected override void DeallocateColumns()
    {
        Contributions.Dispose();
    }

    protected override void SyncObjectToRow()
    {
        Contributions[SoAIndex] = Contribution;
    }

    protected override void SwapBackRow(int removedIndex, int lastIndex)
    {
        if (removedIndex != lastIndex)
        {
            Contributions[removedIndex] = Contributions[lastIndex];
        }
    }
}
