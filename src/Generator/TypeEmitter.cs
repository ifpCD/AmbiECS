using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace AmbiECS.Generator;

static class TypeEmitter
{
    public static string Emit(TypeModel type)
    {
        CodeWriter w = new();
        w.Line("// <auto-generated/>");
        w.Line("#nullable enable annotations");
        w.Line();

        if (type.Errors.Items.Length > 0)
        {
            foreach (string error in type.Errors.Items)
                w.Line("#error AmbiECS: " + error);

            return w.ToString();
        }

        string ambi = $"global::AmbiECS.Ambi<{type.Name}>";
        string contract = $"global::AmbiECS.IAmbiRegistrant<{type.Name}>";

        if (type.Namespace is not null)
        {
            w.Line($"namespace {type.Namespace};");
            w.Line();
        }

        if (!type.HasCleanupAttribute)
            w.Line("[global::Unity.Scripting.LifecycleManagement.NoAutoStaticsCleanup]");

        w.Open($"partial class {type.Name} : {contract}");
        Surface(w, type, ambi, contract);
        Columns(w, type, contract);
        Rows(w, type, contract);
        Properties(w, type, ambi);
        Messages(w, type, ambi);
        Hooks(w);
        w.Close();

        return w.ToString();
    }

    static void Surface(CodeWriter w, TypeModel type, string ambi, string contract)
    {
        w.Line("global::AmbiECS.AmbiSlot _ambiSlot = global::AmbiECS.AmbiSlot.Unassigned;");
        w.Line();

        if (type.HasPendingBits)
        {
            w.Line("ulong _ambiPending;");
            w.Line();
        }

        w.Line($"ref global::AmbiECS.AmbiSlot {contract}.Slot => ref _ambiSlot;");
        w.Line();
        w.Line($"public global::AmbiECS.AmbiHandle Handle => {ambi}.HandleOf(this);");
        w.Line();
        w.Line("public bool IsRegistered => _ambiSlot.IsRegistered;");
        w.Line();
        w.Line("public int Row => _ambiSlot.Row;");
        w.Line();
        w.Line($"public void Register() => {ambi}.Register(this);");
        w.Line();
        w.Line($"public void Deregister() => {ambi}.Deregister(this);");
        w.Line();
        w.Line($"public void MarkDirty() => {ambi}.MarkDirty(this);");

        if (!type.IsBehaviour)
        {
            w.Line();
            w.Line($"public void Release() => {ambi}.Destroy(this);");
        }

        w.Line();
        w.Line($"public static int RegisteredCount => {ambi}.RegisteredCount;");
        w.Line();
        w.Line($"public static int RowCount => {ambi}.RowCount;");
        w.Line();
        w.Line($"public static bool IsEmpty => {ambi}.IsEmpty;");
        w.Line();
        w.Line($"public static global::AmbiECS.AmbiLookup Lookup => {ambi}.Lookup;");
        w.Line();
        w.Line($"public static {ambi}.Registrations Registered => default;");
    }

    static void Columns(CodeWriter w, TypeModel type, string contract)
    {
        ColumnModel[] columns = [.. type.Columns.Items];

        w.Line();
        w.Line($"static int {contract}.InitialCapacity => {type.Capacity};");

        if (type.Fixed)
            w.Line($"static bool {contract}.CanGrow => false;");

        if (!type.RetainColumnsWhenEmpty)
            w.Line($"static bool {contract}.RetainColumnsWhenEmpty => false;");

        w.Line();
        w.Open($"static void {contract}.AllocateColumns(int capacity)");

        foreach (ColumnModel column in columns)
        {
            w.Line(
                column.Storage switch
                {
                    Storage.NativeArray => $"{column.Name} = new({Length(column)}, global::Unity.Collections.Allocator.Persistent);",
                    Storage.ManagedArray => $"{column.Name} = new {column.Element}[{Length(column)}];",
                    _ => $"{column.Name} = new({Length(column)});",
                }
            );
        }

        w.Line("OnColumnsAllocated(capacity);");
        w.Close();

        w.Line();
        w.Open($"static void {contract}.ResizeColumns(int rowCount, int capacity)");

        foreach (ColumnModel column in columns)
        {
            if (column.Kind == ColumnKind.Scratch && column.Length > 0)
                continue; // a fixed length

            w.Line(
                column.Storage switch
                {
                    Storage.NativeArray => $"global::AmbiECS.AmbiColumn.Resize(ref {column.Name}, {Length(column)});",
                    Storage.ManagedArray => $"global::System.Array.Resize(ref {column.Name}, {Length(column)});",
                    _ => $"{column.Name}.capacity = {Length(column)};",
                }
            );
        }

        w.Line("OnColumnsResized(rowCount, capacity);");
        w.Close();

        w.Line();
        w.Open($"static void {contract}.DeallocateColumns()");
        w.Line("OnColumnsDeallocating();");

        foreach (ColumnModel column in columns)
            w.Line(column.Storage == Storage.ManagedArray ? $"{column.Name} = null;" : $"{column.Name}.Dispose();");

        w.Close();
    }

    static void Rows(CodeWriter w, TypeModel type, string contract)
    {
        ColumnModel[] columns = [.. type.Columns.Items];
        GlueModel[] writes = [.. type.Glues.Items.Where(glue => glue.ReadBack is null)];

        w.Line();
        w.Open($"void {contract}.LoadRow(int row)");

        foreach (ColumnModel column in columns)
        {
            if (column.Kind != ColumnKind.State)
                continue;

            w.Line(
                column.Stride == 1
                    ? $"{column.Name}[row] = {column.Initial};"
                    : $"for (int i = row * {column.Stride}, end = i + {column.Stride}; i < end; i++) {column.Name}[i] = {column.Initial};"
            );
        }

        foreach (GlueModel glue in writes)
        {
            ColumnModel column = ColumnOf(columns, glue);

            w.Line(
                column.Storage == Storage.TransformAccessArray
                    ? $"{column.Name}.Add({Value(glue, glue.Member)});"
                    : Write(glue, column, glue.Member)
            );
        }

        if (type.HasPendingBits)
            w.Line("_ambiPending = 0;");

        w.Line("OnRowLoaded(row);");
        w.Close();

        w.Line();
        w.Open($"void {contract}.SyncRow(int row, bool dirty)");

        if (type.HasPendingBits)
        {
            w.Line("ulong pending = _ambiPending;");
            w.Line("_ambiPending = 0;");
            w.Line();
        }

        GlueModel[] untracked = [.. writes.Where(glue => glue.Bit == 0)];

        if (untracked.Length > 0)
        {
            w.Open("if (dirty)");

            foreach (GlueModel glue in untracked)
                w.Line(Write(glue, ColumnOf(columns, glue), glue.Member));

            w.Close();
            w.Line();
        }

        foreach (GlueModel glue in writes)
        {
            if (glue.Bit == 0)
                continue;

            string bit = $"(pending & 0x{glue.Bit:X}UL) != 0";
            w.Line(glue.Tracked ? $"if ({bit})" : $"if (dirty || {bit})");
            w.Line("    " + Write(glue, ColumnOf(columns, glue), glue.Member));
        }

        w.Line("OnRowSynced(row);");
        w.Close();

        ColumnModel[] carried = [.. columns.Where(column => column.Kind != ColumnKind.Scratch)];
        ColumnModel[] appended = [.. carried.Where(column => column.Storage == Storage.TransformAccessArray)];
        ColumnModel[] indexed = [.. carried.Where(column => column.Storage != Storage.TransformAccessArray)];

        w.Line();
        w.Open($"void {contract}.RemoveRow(int row, int lastRow)");

        foreach (ColumnModel column in appended)
            w.Line($"{column.Name}.RemoveAtSwapBack(row);");

        if (indexed.Length > 0)
        {
            w.Open("if (row != lastRow)");

            foreach (ColumnModel column in indexed)
            {
                w.Line(
                    column.Stride == 1
                        ? $"{column.Name}[row] = {column.Name}[lastRow];"
                        : $"global::AmbiECS.AmbiColumn.MoveBlock({column.Name}, lastRow, row, {column.Stride});"
                );
            }

            w.Close();
        }

        w.Line("OnRowRemoved(row, lastRow);");
        w.Close();
    }

    static void Properties(CodeWriter w, TypeModel type, string ambi)
    {
        ColumnModel[] columns = [.. type.Columns.Items];
        GlueModel[] glues = [.. type.Glues.Items];

        foreach (PropertyModel property in type.Properties.Items)
        {
            PartialModel declaration = property.Declaration;

            w.Line();
            w.Open($"{declaration.Modifiers} {declaration.Type} {property.Name}");

            if (declaration.HasGetter)
                w.Line($"{declaration.GetModifiers}get;");

            w.Open($"{declaration.SetModifiers}{declaration.SetKeyword}");
            w.Line($"if (global::System.Collections.Generic.EqualityComparer<{declaration.Type}>.Default.Equals(field, value))");
            w.Line("    return;");
            w.Line();
            w.Line("field = value;");

            if (property.Writes.Items.Length > 0)
            {
                string pend = $"_ambiPending |= 0x{property.Mask:X}UL;";
                string queue = $"{ambi}.MarkPending(this);";

                w.Line();

                if (type.HasSyncHook)
                {
                    w.Line(pend);
                    w.Line(queue);
                }
                else
                {
                    w.Line("int row = _ambiSlot.Row;");
                    w.Line();
                    w.Open("if (row >= 0 && global::AmbiECS.AmbiScheduler.IsIdle)");

                    foreach (int index in property.Writes.Items)
                    {
                        GlueModel glue = glues[index];
                        w.Line(Write(glue, ColumnOf(columns, glue), glue.Member == property.Name ? "value" : glue.Member));
                    }

                    w.Close();
                    w.Open("else");
                    w.Line(pend);
                    w.Line(queue);
                    w.Close();
                }
            }

            w.Close();
            w.Close();
        }

        foreach (GlueModel glue in glues)
        {
            if (glue.ReadBack is not PartialModel declaration)
                continue;

            w.Line();
            w.Open($"{declaration.Modifiers} {declaration.Type} {glue.Member}");
            w.Open($"{declaration.GetModifiers}get");
            w.Line("global::AmbiECS.AmbiScheduler.Complete();");
            w.Line("int row = _ambiSlot.Row;");
            w.Line($"return row < 0 ? default : {glue.Column}[row];");
            w.Close();
            w.Close();
        }
    }

    static void Messages(CodeWriter w, TypeModel type, string ambi)
    {
        foreach (MessageModel message in type.Messages.Items)
        {
            List<string> body = message.Name switch
            {
                "OnEnable" => [$"{ambi}.Register(this);"],
                "OnDisable" => [$"{ambi}.Deregister(this);"],
                "OnDestroy" => [$"{ambi}.Destroy(this);"],
                _ => [$"{ambi}.MarkDirty(this);"], // OnValidate: inspector, undo and animation edits skip the setters
            };

            bool editorOnly = message.Name == "OnValidate";

            if (editorOnly && type.HasPendingBits)
                body.Insert(0, "_ambiPending = ulong.MaxValue;");

            w.Line();

            if (editorOnly)
                w.Directive("#if UNITY_EDITOR");

            if (!message.Override && body.Count == 1)
                w.Line($"void {message.Name}() => {body[0].TrimEnd(';')};");
            else
            {
                w.Open(message.Override ? $"{message.Accessibility} override void {message.Name}()" : $"void {message.Name}()");

                if (message.CallBase)
                    w.Line($"base.{message.Name}();");

                foreach (string line in body)
                    w.Line(line);

                w.Close();
            }

            if (editorOnly)
                w.Directive("#endif");
        }
    }

    // Unimplemented, the compiler removes both these and their calls.
    static void Hooks(CodeWriter w)
    {
        w.Line();
        w.Line("static partial void OnColumnsAllocated(int capacity);");
        w.Line();
        w.Line("static partial void OnColumnsResized(int rowCount, int capacity);");
        w.Line();
        w.Line("static partial void OnColumnsDeallocating();");
        w.Line();
        w.Line("partial void OnRowLoaded(int row);");
        w.Line();
        w.Line("partial void OnRowSynced(int row);");
        w.Line();
        w.Line("partial void OnRowRemoved(int row, int lastRow);");
    }

    static ColumnModel ColumnOf(ColumnModel[] columns, GlueModel glue) => columns.First(column => column.Name == glue.Column);

    static string Write(GlueModel glue, ColumnModel column, string member)
    {
        if (!glue.Sequence)
            return $"{column.Name}[row] = {Value(glue, member)};";

        string write = glue.Targets ? "WriteHandles" : "WriteValues";
        string span = glue.IsList ? $"global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan({member})" : member;
        return $"global::AmbiECS.AmbiColumn.{write}<{glue.Element}>({column.Name}, row, {column.Stride}, {span});";
    }

    static string Value(GlueModel glue, string member) => glue.Targets ? $"global::AmbiECS.Ambi<{glue.Element}>.HandleOf({member})" : member;

    static string Length(ColumnModel column)
    {
        if (column.Kind == ColumnKind.Scratch)
            return column.Length > 0 ? column.Length.ToString(CultureInfo.InvariantCulture) : Times(column.PerRow);

        return Times(column.Stride);
    }

    static string Times(int factor) => factor == 1 ? "capacity" : $"capacity * {factor}";

    sealed class CodeWriter
    {
        readonly StringBuilder _text = new();
        int _depth;

        public void Line(string line = "")
        {
            if (line.Length > 0)
                _text.Append(' ', 4 * _depth).Append(line);

            _text.Append('\n');
        }

        public void Directive(string line) => _text.Append(line).Append('\n');

        public void Open(string line)
        {
            Line(line);
            Line("{");
            _depth++;
        }

        public void Close()
        {
            _depth--;
            Line("}");
        }

        public override string ToString() => _text.ToString();
    }
}
